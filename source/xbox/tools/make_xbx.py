#!/usr/bin/env python3
"""Generate include/xbox_udata_assets.h: dashboard icons (XPR0 / DXT1) for the
UDATA save folders, built from tools/sonicr.ico.

  TitleImage.xbx  128x128   (shown for the game)
  saveimage.xbx    64x64    (shown for each save)
"""
import struct, sys, os
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
ico = Image.open(os.path.join(here, "sonicr.ico")).convert("RGBA")

def render(size):
    bg = Image.new("RGBA", (size, size), (16, 24, 64, 255))
    im = ico.resize((size, size), Image.NEAREST if size % 32 == 0 else Image.LANCZOS)
    bg.alpha_composite(im)
    return bg.convert("RGB")

def rgb565(c):
    return ((c[0] >> 3) << 11) | ((c[1] >> 2) << 5) | (c[2] >> 3)

def from565(v):
    r = (v >> 11) & 31; g = (v >> 5) & 63; b = v & 31
    return ((r << 3) | (r >> 2), (g << 2) | (g >> 4), (b << 3) | (b >> 2))

def dxt1(img):
    w, h = img.size
    px = img.load()
    out = bytearray()
    for by in range(0, h, 4):
        for bx in range(0, w, 4):
            blk = [px[bx + x, by + y] for y in range(4) for x in range(4)]
            lo = min(blk, key=lambda c: c[0] * 3 + c[1] * 6 + c[2])
            hi = max(blk, key=lambda c: c[0] * 3 + c[1] * 6 + c[2])
            c0, c1 = rgb565(hi), rgb565(lo)
            if c0 < c1:
                c0, c1 = c1, c0
            if c0 == c1:
                out += struct.pack("<HHI", c0, c1, 0)
                continue
            p0, p1 = from565(c0), from565(c1)
            pal = [p0, p1,
                   tuple((2 * a + b) // 3 for a, b in zip(p0, p1)),
                   tuple((a + 2 * b) // 3 for a, b in zip(p0, p1))]
            idx = 0
            for i, c in enumerate(blk):
                best = min(range(4), key=lambda k: sum((c[j] - pal[k][j]) ** 2 for j in range(3)))
                idx |= best << (2 * i)
            out += struct.pack("<HHI", c0, c1, idx)
    return bytes(out)

def xpr(size):
    data = dxt1(render(size))
    lg = size.bit_length() - 1
    fmt = 0x02 | (2 << 4) | (0x0C << 8) | (1 << 16) | (lg << 20) | (lg << 24)
    hdr_size = 0x800
    total = hdr_size + len(data)
    hdr = struct.pack("<4sIIIIIIII", b"XPR0", total, hdr_size,
                      0x00040001, 0, 0, fmt, 0, 0xFFFFFFFF)
    hdr += b"\0" * (hdr_size - len(hdr))
    return hdr + data

def carr(name, b):
    s = "static const unsigned char %s[%d] = {\n" % (name, len(b))
    for i in range(0, len(b), 16):
        s += "  " + ",".join("0x%02x" % x for x in b[i:i + 16]) + ",\n"
    return s + "};\n"

out = "/* generated by tools/make_xbx.py - do not edit */\n"
out += carr("xb_titleimage_xbx", xpr(128))
out += carr("xb_saveimage_xbx", xpr(64))
dst = os.path.join(here, "..", "include", "xbox_udata_assets.h")
open(dst, "w").write(out)
print("wrote", dst)
